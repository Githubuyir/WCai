export function parsePlayers(lineupStr) {
  if (!lineupStr) return [];
  return lineupStr
    .split(/[;,]/)
    .map(p => p.trim())
    .filter(p => p.length > 0);
}

export function getStartingXI(code) {
  const team = TEAMS_LINEUPS[code];
  if (!team) return [];
  const players = parsePlayers(team.lineup);
  return getStartingXIForFormation(team.formation, players);
}
